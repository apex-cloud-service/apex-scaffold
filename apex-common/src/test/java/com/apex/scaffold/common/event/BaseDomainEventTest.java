package com.apex.scaffold.common.event;

import static org.assertj.core.api.Assertions.assertThat;

import java.time.LocalDateTime;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Nested;
import org.junit.jupiter.api.Test;

/**
 * {@link BaseDomainEvent} 的单元测试类
 *
 * <p>测试领域事件基类的核心方法：标记处理、过期判断、事件名称等。
 *
 * @author Apex Team
 * @version 1.0.0
 * @since 1.0.0
 */
@DisplayName("BaseDomainEvent 单元测试")
class BaseDomainEventTest {

    /** 测试用的具体事件实现 */
    static class TestDomainEvent extends BaseDomainEvent {

        private final String sourceId;

        /**
         * 创建 {@code TestDomainEvent} 实例。
         * @param eventType 参数 {@code eventType}
         * @param traceId 参数 {@code traceId}
         * @param sourceId 参数 {@code sourceId}
         */
        TestDomainEvent(String eventType, String traceId, String sourceId) {
            super(eventType, traceId);
            this.sourceId = sourceId;
        }

        /**
         * 创建 {@code TestDomainEvent} 实例。
         * @param eventType 参数 {@code eventType}
         */
        TestDomainEvent(String eventType) {
            super(eventType);
            this.sourceId = "test-source";
        }

        /** {@inheritDoc} */
        @Override
        public String getSourceId() {
            return sourceId;
        }
    }

    @Nested
    @DisplayName("事件创建")
    class CreationTests {

        /**
         * 执行 {@code eventIdShouldNotBeNull} 操作。
         */
        @Test
        @DisplayName("创建事件时 eventId 不应为空")
        void eventIdShouldNotBeNull() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            assertThat(event.getEventId()).isNotBlank();
        }

        /**
         * 创建{@code dAtShouldNotBeNull}。
         */
        @Test
        @DisplayName("创建事件时 createdAt 不应为空")
        void createdAtShouldNotBeNull() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            assertThat(event.getCreatedAt()).isNotNull();
        }

        /**
         * 执行 {@code traceIdShouldBeSet} 操作。
         */
        @Test
        @DisplayName("创建事件时 traceId 应被正确设置")
        void traceIdShouldBeSet() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT", "trace-001", "src-1");
            assertThat(event.getTraceId()).isEqualTo("trace-001");
        }

        /**
         * 执行 {@code autoGeneratedTraceIdShouldNotBeBlank} 操作。
         */
        @Test
        @DisplayName("自动生成 traceId 时不应为空")
        void autoGeneratedTraceIdShouldNotBeBlank() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            assertThat(event.getTraceId()).isNotBlank();
        }

        /**
         * 执行 {@code eventTypeShouldBeSet} 操作。
         */
        @Test
        @DisplayName("eventType 应被正确设置")
        void eventTypeShouldBeSet() {
            TestDomainEvent event = new TestDomainEvent("USER_LOGIN");
            assertThat(event.getEventType()).isEqualTo("USER_LOGIN");
        }
    }

    @Nested
    @DisplayName("markAsProcessed 方法")
    class MarkAsProcessedTests {

        /**
         * 执行 {@code newEventShouldNotBeProcessed} 操作。
         */
        @Test
        @DisplayName("新创建的事件应未被处理")
        void newEventShouldNotBeProcessed() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            assertThat(event.isProcessed()).isFalse();
        }

        /**
         * 执行 {@code shouldBeMarkedAsProcessed} 操作。
         */
        @Test
        @DisplayName("调用 markAsProcessed 后应标记为已处理")
        void shouldBeMarkedAsProcessed() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            event.markAsProcessed();
            assertThat(event.isProcessed()).isTrue();
        }

        /**
         * 执行 {@code shouldNotChangeWhenAlreadyProcessed} 操作。
         */
        @Test
        @DisplayName("已处理的事件不应被重复标记影响")
        void shouldNotChangeWhenAlreadyProcessed() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            event.markAsProcessed();
            event.markAsProcessed();
            assertThat(event.isProcessed()).isTrue();
        }
    }

    @Nested
    @DisplayName("isExpired 方法")
    class IsExpiredTests {

        /**
         * 执行 {@code shouldNotBeExpiredImmediately} 操作。
         */
        @Test
        @DisplayName("刚创建的事件（0分钟）不应过期")
        void shouldNotBeExpiredImmediately() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            assertThat(event.isExpired(60)).isFalse();
        }

        /**
         * 执行 {@code shouldBeExpiredWhenPastThreshold} 操作。
         */
        @Test
        @DisplayName("事件创建于参考时间前30分钟，过期阈值10分钟应已过期")
        void shouldBeExpiredWhenPastThreshold() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            LocalDateTime referenceTime = event.getCreatedAt().plusMinutes(15);
            assertThat(event.isExpired(10, referenceTime)).isTrue();
        }

        /**
         * 执行 {@code shouldNotBeExpiredWhenWithinThreshold} 操作。
         */
        @Test
        @DisplayName("事件创建于参考时间前5分钟，过期阈值10分钟应未过期")
        void shouldNotBeExpiredWhenWithinThreshold() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            LocalDateTime referenceTime = event.getCreatedAt().plusMinutes(5);
            assertThat(event.isExpired(10, referenceTime)).isFalse();
        }
    }

    @Nested
    @DisplayName("getEventName 方法")
    class GetEventNameTests {

        /**
         * 执行 {@code shouldReturnSimpleClassName} 操作。
         */
        @Test
        @DisplayName("getEventName 应返回类名")
        void shouldReturnSimpleClassName() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            assertThat(event.getEventName()).isEqualTo("TestDomainEvent");
        }
    }

    @Nested
    @DisplayName("getSourceId 方法")
    class GetSourceIdTests {

        /**
         * 执行 {@code shouldReturnSetSourceId} 操作。
         */
        @Test
        @DisplayName("getSourceId 应返回构造时设置的 sourceId")
        void shouldReturnSetSourceId() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT", "trace-1", "aggregate-42");
            assertThat(event.getSourceId()).isEqualTo("aggregate-42");
        }
    }

    @Nested
    @DisplayName("toString 方法")
    class ToStringTests {

        /**
         * 执行 {@code shouldContainEventId} 操作。
         */
        @Test
        @DisplayName("toString 应包含 eventId")
        void shouldContainEventId() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            assertThat(event.toString()).contains(event.getEventId());
        }

        /**
         * 执行 {@code shouldContainEventType} 操作。
         */
        @Test
        @DisplayName("toString 应包含 eventType")
        void shouldContainEventType() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            assertThat(event.toString()).contains("TEST_EVENT");
        }

        /**
         * 执行 {@code shouldContainProcessedStatus} 操作。
         */
        @Test
        @DisplayName("toString 应包含 processed 状态")
        void shouldContainProcessedStatus() {
            TestDomainEvent event = new TestDomainEvent("TEST_EVENT");
            assertThat(event.toString()).contains("processed=false");
        }
    }
}
