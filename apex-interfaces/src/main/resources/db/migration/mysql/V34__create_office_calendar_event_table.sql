-- 日历事件表
CREATE TABLE IF NOT EXISTS office_calendar_event (
    id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',
    tenant_id BIGINT NOT NULL COMMENT '租户ID',
    platform VARCHAR(50) NOT NULL COMMENT '办公平台类型（feishu/dingtalk/wecom）',
    platform_event_id VARCHAR(200) NOT NULL COMMENT '平台中的事件ID',
    title VARCHAR(500) NOT NULL COMMENT '事件标题',
    description TEXT COMMENT '事件描述',
    event_type VARCHAR(50) NOT NULL COMMENT '事件类型（MEETING/TASK/REMINDER/VACATION/BIRTHDAY/OTHER）',
    organizer_id VARCHAR(100) NOT NULL COMMENT '事件创建人ID',
    organizer_name VARCHAR(100) NOT NULL COMMENT '事件创建人姓名',
    start_time DATETIME NOT NULL COMMENT '开始时间',
    end_time DATETIME NOT NULL COMMENT '结束时间',
    is_all_day TINYINT(1) DEFAULT 0 COMMENT '是否全天事件（0-否，1-是）',
    location VARCHAR(500) COMMENT '事件地点',
    participant_ids TEXT COMMENT '参与人ID列表（JSON格式）',
    participant_names TEXT COMMENT '参与人姓名列表（JSON格式）',
    meeting_room_id VARCHAR(100) COMMENT '会议室ID',
    reminder_minutes INT DEFAULT -1 COMMENT '提醒时间（分钟数，-1表示不提醒）',
    is_recurring TINYINT(1) DEFAULT 0 COMMENT '是否重复事件（0-否，1-是）',
    recurrence_rule TEXT COMMENT '重复规则（RRULE格式）',
    status VARCHAR(50) DEFAULT 'TENTATIVE' COMMENT '事件状态（TENTATIVE/CONFIRMED/CANCELLED）',
    version INT DEFAULT 0 COMMENT '乐观锁版本号',
    deleted TINYINT(1) DEFAULT 0 COMMENT '逻辑删除标记（0-未删除，1-已删除）',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_tenant_id (tenant_id),
    INDEX idx_platform_event_id (platform, platform_event_id),
    INDEX idx_organizer_id (organizer_id),
    INDEX idx_time_range (start_time, end_time),
    INDEX idx_meeting_room (meeting_room_id, start_time, end_time),
    INDEX idx_status (status),
    INDEX idx_create_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='办公平台日历事件表';
