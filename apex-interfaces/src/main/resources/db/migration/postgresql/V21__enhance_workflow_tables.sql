-- ============================================================
-- Flyway 迁移脚本 V21：增强工作流表
-- ============================================================
-- 执行日期: 2026-09-04
-- 目标: 为工作流表添加高级功能支持（回退、转办、挂起、超时处理）
-- ============================================================

-- 为流程实例表添加挂起相关字段
ALTER TABLE wf_process_instance
    ADD COLUMN IF NOT EXISTS suspended SMALLINT DEFAULT 0,
    ADD COLUMN IF NOT EXISTS suspend_reason VARCHAR(500),
    ADD COLUMN IF NOT EXISTS suspend_time TIMESTAMP,
    ADD COLUMN IF NOT EXISTS resume_time TIMESTAMP;

-- 为流程实例表添加状态索引（加速按状态查询）
CREATE INDEX IF NOT EXISTS idx_process_instance_status ON wf_process_instance(status);

-- 为流程实例表添加挂起状态索引
CREATE INDEX IF NOT EXISTS idx_process_instance_suspended ON wf_process_instance(suspended);

-- 为任务表添加超时相关字段
ALTER TABLE wf_task
    ADD COLUMN IF NOT EXISTS timeout_at TIMESTAMP,
    ADD COLUMN IF NOT EXISTS timeout_action VARCHAR(50),
    ADD COLUMN IF NOT EXISTS timeout_handled SMALLINT DEFAULT 0;

-- 为任务表添加转办/委派相关字段
ALTER TABLE wf_task
    ADD COLUMN IF NOT EXISTS transferred_from BIGINT,
    ADD COLUMN IF NOT EXISTS transferred_time TIMESTAMP,
    ADD COLUMN IF NOT EXISTS delegated_from BIGINT,
    ADD COLUMN IF NOT EXISTS delegated_time TIMESTAMP,
    ADD COLUMN IF NOT EXISTS delegation_completed SMALLINT DEFAULT 0;

-- 为任务表添加复合索引（加速待办任务查询）
CREATE INDEX IF NOT EXISTS idx_task_status_assignee ON wf_task(status, assignee_id);

-- 为任务表添加超时任务查询索引
CREATE INDEX IF NOT EXISTS idx_task_timeout ON wf_task(timeout_at, timeout_handled);

-- 为任务表添加转办来源索引
CREATE INDEX IF NOT EXISTS idx_task_transferred_from ON wf_task(transferred_from);

-- 为审批记录表添加索引（加速按实例ID查询）
CREATE INDEX IF NOT EXISTS idx_approval_record_instance ON wf_approval_record(process_instance_id);

-- 为审批记录表添加审批人索引
CREATE INDEX IF NOT EXISTS idx_approval_record_approver ON wf_approval_record(approver_id);

-- 创建任务历史表（用于记录任务流转历史）
CREATE TABLE IF NOT EXISTS wf_task_history (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    task_id BIGINT NOT NULL,
    process_instance_id BIGINT NOT NULL,
    action_type VARCHAR(50) NOT NULL,
    operator_id BIGINT,
    operator_name VARCHAR(100),
    from_status VARCHAR(50),
    to_status VARCHAR(50),
    comment VARCHAR(500),
    action_time TIMESTAMP NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_task_history_action_time ON wf_task_history (action_time);
CREATE INDEX IF NOT EXISTS idx_task_history_instance_id ON wf_task_history (process_instance_id);
CREATE INDEX IF NOT EXISTS idx_task_history_task_id ON wf_task_history (task_id);

-- 创建流程回退历史表
CREATE TABLE IF NOT EXISTS wf_rollback_history (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    process_instance_id BIGINT NOT NULL,
    from_node_id VARCHAR(100) NOT NULL,
    to_node_id VARCHAR(100) NOT NULL,
    rollback_reason VARCHAR(500),
    operator_id BIGINT NOT NULL,
    operator_name VARCHAR(100),
    rollback_time TIMESTAMP NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_rollback_history_time ON wf_rollback_history (rollback_time);
CREATE INDEX IF NOT EXISTS idx_rollback_history_instance ON wf_rollback_history (process_instance_id);

-- 为 wf_definition 表添加版本管理字段（支持未来版本管理功能）
ALTER TABLE wf_workflow_definition
    ADD COLUMN IF NOT EXISTS version INT DEFAULT 1,
    ADD COLUMN IF NOT EXISTS is_latest SMALLINT DEFAULT 1,
    ADD COLUMN IF NOT EXISTS previous_version_id BIGINT;

-- 为 wf_definition 表添加版本索引
CREATE INDEX IF NOT EXISTS idx_definition_code_version ON wf_workflow_definition(workflow_code, version);
CREATE INDEX IF NOT EXISTS idx_definition_is_latest ON wf_workflow_definition(is_latest);

-- 插入配置说明数据（可选，用于记录迁移信息）
INSERT INTO sys_config (config_name, config_key, config_value, config_type, remark, create_time, update_time, version, deleted)
VALUES ('工作流引擎版本', 'workflow.version', 'v1.4.0', 1, '工作流引擎版本：支持回退、转办、挂起、超时处理', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 0, 0)
ON CONFLICT (config_key) DO UPDATE SET config_value = EXCLUDED.config_value, remark = EXCLUDED.remark, update_time = EXCLUDED.update_time;

