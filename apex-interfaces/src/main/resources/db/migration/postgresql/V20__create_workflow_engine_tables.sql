-- 脚本用途：创建轻量工作流引擎的核心表（工作流定义、流程实例、任务、审批记录）
-- 版本：v1.3.0 新增 Enterprise 版商业化卖点
-- 依赖：License 特性门控 workflow（仅 Enterprise 版可用）

-- 工作流定义表
CREATE TABLE IF NOT EXISTS wf_workflow_definition (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    workflow_code VARCHAR(100) NOT NULL,
    workflow_name VARCHAR(200) NOT NULL,
    version INT NOT NULL DEFAULT 1,
    node_config_json TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    description VARCHAR(500),
    tenant_id VARCHAR(64) NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted SMALLINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_workflow_code_version UNIQUE (workflow_code, version, deleted)
);
CREATE INDEX IF NOT EXISTS idx_wf_workflow_definition_idx_tenant_status ON wf_workflow_definition (tenant_id, status);
CREATE INDEX IF NOT EXISTS idx_wf_workflow_definition_idx_update_time ON wf_workflow_definition (update_time);

-- 流程实例表
CREATE TABLE IF NOT EXISTS wf_process_instance (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    workflow_definition_id BIGINT NOT NULL,
    business_key VARCHAR(200) NOT NULL,
    current_node_key VARCHAR(100),
    status VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    initiator_id BIGINT NOT NULL,
    context_json TEXT,
    start_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    end_time TIMESTAMP,
    tenant_id VARCHAR(64) NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted SMALLINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_business_key UNIQUE (business_key, deleted)
);
CREATE INDEX IF NOT EXISTS idx_wf_process_instance_idx_workflow_def ON wf_process_instance (workflow_definition_id);
CREATE INDEX IF NOT EXISTS idx_wf_process_instance_idx_tenant_initiator ON wf_process_instance (tenant_id, initiator_id);
CREATE INDEX IF NOT EXISTS idx_wf_process_instance_idx_status ON wf_process_instance (status);
CREATE INDEX IF NOT EXISTS idx_wf_process_instance_idx_start_time ON wf_process_instance (start_time);

-- 任务表
CREATE TABLE IF NOT EXISTS wf_task (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    process_instance_id BIGINT NOT NULL,
    node_key VARCHAR(100) NOT NULL,
    node_name VARCHAR(200) NOT NULL,
    assignee_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    due_date TIMESTAMP,
    completed_time TIMESTAMP,
    tenant_id VARCHAR(64) NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted SMALLINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_wf_task_idx_process_instance ON wf_task (process_instance_id);
CREATE INDEX IF NOT EXISTS idx_wf_task_idx_tenant_assignee_status ON wf_task (tenant_id, assignee_id, status);
CREATE INDEX IF NOT EXISTS idx_wf_task_idx_due_date ON wf_task (due_date);
CREATE INDEX IF NOT EXISTS idx_wf_task_idx_create_time ON wf_task (create_time);

-- 审批记录表
CREATE TABLE IF NOT EXISTS wf_approval_record (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    process_instance_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    approver_id BIGINT NOT NULL,
    action VARCHAR(20) NOT NULL,
    comment VARCHAR(1000),
    tenant_id VARCHAR(64) NOT NULL,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted SMALLINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_wf_approval_record_idx_process_instance ON wf_approval_record (process_instance_id);
CREATE INDEX IF NOT EXISTS idx_wf_approval_record_idx_task ON wf_approval_record (task_id);
CREATE INDEX IF NOT EXISTS idx_wf_approval_record_idx_tenant_approver ON wf_approval_record (tenant_id, approver_id);
CREATE INDEX IF NOT EXISTS idx_wf_approval_record_idx_create_time ON wf_approval_record (create_time);

-- 添加外键约束
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_process_workflow_def'
          AND conrelid = 'wf_process_instance'::regclass
    ) THEN
        ALTER TABLE wf_process_instance
            ADD CONSTRAINT fk_process_workflow_def
            FOREIGN KEY (workflow_definition_id)
            REFERENCES wf_workflow_definition (id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_task_process_instance'
          AND conrelid = 'wf_task'::regclass
    ) THEN
        ALTER TABLE wf_task
            ADD CONSTRAINT fk_task_process_instance
            FOREIGN KEY (process_instance_id)
            REFERENCES wf_process_instance (id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_approval_process_instance'
          AND conrelid = 'wf_approval_record'::regclass
    ) THEN
        ALTER TABLE wf_approval_record
            ADD CONSTRAINT fk_approval_process_instance
            FOREIGN KEY (process_instance_id)
            REFERENCES wf_process_instance (id);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_approval_task'
          AND conrelid = 'wf_approval_record'::regclass
    ) THEN
        ALTER TABLE wf_approval_record
            ADD CONSTRAINT fk_approval_task
            FOREIGN KEY (task_id)
            REFERENCES wf_task (id);
    END IF;
END $$;
