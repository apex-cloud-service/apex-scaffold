-- 文档信息表
CREATE TABLE IF NOT EXISTS office_document_info (
    id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',
    tenant_id BIGINT NOT NULL COMMENT '租户ID',
    platform VARCHAR(50) NOT NULL COMMENT '办公平台类型（feishu/dingtalk/wecom）',
    platform_document_id VARCHAR(200) NOT NULL COMMENT '平台中的文档ID',
    document_type VARCHAR(50) NOT NULL COMMENT '文档类型（DOC/SHEET/SLIDE/MINDMAP/FOLDER/FILE）',
    title VARCHAR(500) NOT NULL COMMENT '文档标题',
    path VARCHAR(1000) COMMENT '文档路径',
    url VARCHAR(1000) COMMENT '文档URL',
    owner_id VARCHAR(100) NOT NULL COMMENT '文档所有者ID',
    owner_name VARCHAR(100) NOT NULL COMMENT '文档所有者姓名',
    parent_folder_id VARCHAR(200) COMMENT '父文件夹ID',
    file_size BIGINT COMMENT '文档大小（字节）',
    file_extension VARCHAR(50) COMMENT '文档扩展名',
    mime_type VARCHAR(100) COMMENT '文档MIME类型',
    is_folder TINYINT(1) DEFAULT 0 COMMENT '是否为文件夹（0-否，1-是）',
    permission VARCHAR(50) DEFAULT 'PRIVATE' COMMENT '权限类型（PRIVATE/PUBLIC/SHARED）',
    collaborator_ids TEXT COMMENT '协作者ID列表（JSON格式）',
    version VARCHAR(50) COMMENT '文档版本号',
    last_modified_by_id VARCHAR(100) COMMENT '最后修改人ID',
    last_modified_by_name VARCHAR(100) COMMENT '最后修改人姓名',
    last_modified_time DATETIME COMMENT '最后修改时间',
    is_archived TINYINT(1) DEFAULT 0 COMMENT '是否已归档（0-否，1-是）',
    version_number INT DEFAULT 0 COMMENT '乐观锁版本号',
    deleted TINYINT(1) DEFAULT 0 COMMENT '逻辑删除标记（0-未删除，1-已删除）',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_tenant_id (tenant_id),
    INDEX idx_platform_document_id (platform, platform_document_id),
    INDEX idx_owner_id (owner_id),
    INDEX idx_parent_folder_id (parent_folder_id),
    INDEX idx_title (title(100)),
    INDEX idx_is_archived (is_archived),
    INDEX idx_create_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='办公平台文档信息表';
