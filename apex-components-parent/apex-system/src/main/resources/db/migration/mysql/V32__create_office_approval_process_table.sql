-- 审批流程表
CREATE TABLE IF NOT EXISTS office_approval_process (
    id BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '主键ID',
    tenant_id BIGINT NOT NULL COMMENT '租户ID',
    platform VARCHAR(50) NOT NULL COMMENT '办公平台类型（feishu/dingtalk/wecom）',
    platform_instance_id VARCHAR(200) NOT NULL COMMENT '平台中的审批实例ID',
    process_instance_id VARCHAR(200) NOT NULL COMMENT '业务流程实例ID',
    template_id VARCHAR(200) NOT NULL COMMENT '审批模板ID',
    title VARCHAR(500) NOT NULL COMMENT '审批标题',
    initiator_id VARCHAR(100) NOT NULL COMMENT '发起人ID',
    initiator_name VARCHAR(100) NOT NULL COMMENT '发起人姓名',
    status VARCHAR(50) NOT NULL COMMENT '审批状态（PENDING/IN_PROGRESS/APPROVED/REJECTED/CANCELLED/TRANSFERRED）',
    form_data TEXT COMMENT '审批表单数据（JSON格式）',
    records TEXT COMMENT '审批记录列表（JSON格式）',
    current_approver_ids TEXT COMMENT '当前审批人ID列表（JSON格式）',
    initiate_time DATETIME NOT NULL COMMENT '审批发起时间',
    complete_time DATETIME COMMENT '审批完成时间',
    version INT DEFAULT 0 COMMENT '乐观锁版本号',
    deleted TINYINT(1) DEFAULT 0 COMMENT '逻辑删除标记（0-未删除，1-已删除）',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_tenant_id (tenant_id),
    INDEX idx_platform_instance_id (platform, platform_instance_id),
    INDEX idx_process_instance_id (process_instance_id),
    INDEX idx_initiator_id (initiator_id),
    INDEX idx_status (status),
    INDEX idx_create_time (create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='办公平台审批流程表';
