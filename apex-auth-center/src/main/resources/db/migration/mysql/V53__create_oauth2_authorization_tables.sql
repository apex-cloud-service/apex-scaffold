CREATE TABLE oauth2_authorization (
    id VARCHAR(100) NOT NULL,
    registered_client_id VARCHAR(100) NOT NULL,
    client_id VARCHAR(100) NOT NULL,
    principal_name VARCHAR(200) NOT NULL,
    authorization_grant_type VARCHAR(50) NOT NULL,
    authorized_scopes VARCHAR(1000) NOT NULL,
    redirect_uri VARCHAR(1000),
    code_challenge VARCHAR(128),
    code_challenge_method VARCHAR(10),
    authorization_code_hash CHAR(64),
    authorization_code_expires_at TIMESTAMP NULL,
    access_token_hash CHAR(64),
    access_token_value TEXT,
    access_token_expires_at TIMESTAMP NULL,
    refresh_token_hash CHAR(64),
    refresh_token_value TEXT,
    refresh_token_expires_at TIMESTAMP NULL,
    revoked TINYINT(1) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_oauth2_authorization_code_hash (authorization_code_hash),
    UNIQUE KEY uk_oauth2_access_token_hash (access_token_hash),
    UNIQUE KEY uk_oauth2_refresh_token_hash (refresh_token_hash),
    KEY idx_oauth2_authorization_client (client_id),
    KEY idx_oauth2_authorization_principal (principal_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
